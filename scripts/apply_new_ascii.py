lines = RAW_ASCII.strip().split("\n")
print(f"Total lines: {len(lines)}")
print(f"Max width: {max(len(l) for l in lines)}")

# Downscale to 25 lines x 40 columns
step_y = len(lines) / 25.0
max_w = max(len(l) for l in lines)
step_x = max_w / 40.0

downscaled = []
for i in range(25):
    y_idx = int(i * step_y)
    line = lines[min(y_idx, len(lines)-1)]
    row_chars = []
    for j in range(40):
        x_idx = int(j * step_x)
        char = line[min(x_idx, len(line)-1)] if x_idx < len(line) else " "
        row_chars.append(char)
    downscaled.append("".join(row_chars))

escaped = [html.escape(l) for l in downscaled]

with open("assets/ascii_dark.txt", "w", encoding="utf-8") as f:
    f.write("\n".join(escaped))

with open("assets/ascii_light.txt", "w", encoding="utf-8") as f:
    f.write("\n".join(escaped))

print("New downscaled ASCII applied successfully!")
